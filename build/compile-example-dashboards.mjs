// Compile the shipped example-Dashboard catalogue (#506) into a checked-in
// generated module the single-file build embeds like any other source
// import. `examples/dashboard-manifest.json` is the maintained source of
// truth (ordered `{file, name}` entries); this script validates every entry
// structurally (existence, JSON-parseability, minimal portable-bundle shape)
// so a missing, malformed, or stale example cannot ship unnoticed, then
// writes the raw file text alongside each entry — the exact string the real
// File-menu import already knows how to decode, so nothing here forks a
// second importer.
//
// Deep schema/semantic validation (does the bundle satisfy
// portable-bundle-v2, exactly one Dashboard, etc.) is asserted by
// `tests/unit/example-dashboards.test.ts`, which decodes the generated
// output through the same `decodePortableBundleJson` the app uses — this
// script only guards what plain JSON.parse can catch, so it stays runnable
// under plain `node` with no TypeScript/Ajv dependency.
//
// Run:
//   node build/compile-example-dashboards.mjs           (write)
//   node build/compile-example-dashboards.mjs --check    (CI gate)

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, relative, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const examplesDir = resolve(root, 'examples');
const manifestPath = resolve(examplesDir, 'dashboard-manifest.json');
const generatedPath = resolve(root, 'src/generated/example-dashboards.ts');
const HEADER = '// Generated by build/compile-example-dashboards.mjs. Do not edit.\n';

export async function loadManifest(path = manifestPath) {
  let raw;
  try { raw = await readFile(path, 'utf8'); } catch {
    throw new Error(`missing manifest: ${relative(root, path)}`);
  }
  let manifest;
  try { manifest = JSON.parse(raw); } catch (error) {
    throw new Error(`malformed manifest JSON (${relative(root, path)}): ${error.message}`);
  }
  if (!Array.isArray(manifest) || manifest.length === 0) {
    throw new Error(`manifest must be a non-empty array: ${relative(root, path)}`);
  }
  const seenFiles = new Set();
  for (const entry of manifest) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      throw new Error(`manifest entry must be an object: ${JSON.stringify(entry)}`);
    }
    const { file, name, ...rest } = entry;
    if (Object.keys(rest).length) throw new Error(`manifest entry has unknown keys: ${Object.keys(rest).join(', ')}`);
    if (typeof file !== 'string' || !file) throw new Error(`manifest entry needs a non-empty "file": ${JSON.stringify(entry)}`);
    if (typeof name !== 'string' || !name) throw new Error(`manifest entry needs a non-empty "name": ${JSON.stringify(entry)}`);
    if (seenFiles.has(file)) throw new Error(`duplicate manifest file entry: ${file}`);
    seenFiles.add(file);
  }
  return manifest;
}

export async function loadEntry({ file, name }, dir = examplesDir) {
  const path = resolve(dir, file);
  let json;
  try { json = await readFile(path, 'utf8'); } catch {
    throw new Error(`example file missing: examples/${file}`);
  }
  let document;
  try { document = JSON.parse(json); } catch (error) {
    throw new Error(`example is not valid JSON (examples/${file}): ${error.message}`);
  }
  if (!document || typeof document !== 'object' || !Array.isArray(document.dashboards) || document.dashboards.length === 0) {
    throw new Error(`example has no dashboards array (examples/${file})`);
  }
  if (!Array.isArray(document.queries)) throw new Error(`example has no queries array (examples/${file})`);
  return { file, name, json };
}

export async function loadExampleDashboards({ manifestPath: manifestOverride, examplesDir: dirOverride } = {}) {
  const manifest = await loadManifest(manifestOverride);
  const entries = [];
  for (const item of manifest) entries.push(await loadEntry(item, dirOverride));
  return entries;
}

function generatedSource(entries) {
  const rows = entries
    .map(({ file, name, json }) => `  { file: ${JSON.stringify(file)}, name: ${JSON.stringify(name)}, json: ${JSON.stringify(json)} },`)
    .join('\n');
  return `${HEADER}export interface ExampleDashboardEntry {\n`
    + '  readonly file: string;\n  readonly name: string;\n  readonly json: string;\n}\n\n'
    + `export const EXAMPLE_DASHBOARDS: readonly ExampleDashboardEntry[] = [\n${rows}\n];\n`;
}

export async function checkOrWrite(check) {
  const entries = await loadExampleDashboards();
  const source = generatedSource(entries);
  await mkdir(dirname(generatedPath), { recursive: true });
  if (check) {
    let current = '';
    try { current = await readFile(generatedPath, 'utf8'); } catch { /* missing is stale */ }
    if (current !== source) {
      console.error('stale generated example-dashboards artifact: ' + relative(root, generatedPath));
      process.exitCode = 1;
      return false;
    }
    return true;
  }
  await writeFile(generatedPath, source);
  console.log('generated ' + relative(root, generatedPath));
  return true;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) checkOrWrite(process.argv.includes('--check')).catch((error) => {
  console.error(error);
  process.exit(1);
});
